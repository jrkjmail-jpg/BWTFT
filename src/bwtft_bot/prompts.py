def story_generation_prompt(
    child_info: str,
    selected_theme: str,
    pages_count: int,
) -> str:
    return f"""Создай персонализированную детскую сказку.

Информация о ребёнке в свободной форме:
{child_info}

Выбранная тематика сказки:
{selected_theme}

Количество страниц: {pages_count}.

Требования к структуре:
- 15-20% страниц: знакомство с ребёнком и обычным миром.
- 10-15% страниц: волшебное событие или начало приключения.
- 40-50% страниц: основное развитие истории.
- 10-15% страниц: главное испытание или кульминация.
- 5-10% страниц: успешное завершение.
- 5-10% страниц: возвращение домой и спокойный эмоциональный финал.

Правила страниц:
- каждая страница содержит одно основное действие, одну визуальную сцену и понятную эмоцию;
- язык простой, детский, добрый;
- текст каждой страницы 300-700 символов;
- каждая страница должна звучать как отдельная страница детской книги;
- переходы между страницами плавные.

Верни только JSON без markdown. Формат:
{{
  "child_name": "имя ребёнка или null",
  "pages": [
    {{
      "page_number": 1,
      "page_text": "текст страницы"
    }}
  ]
}}
"""


def story_revision_prompt(
    child_info: str,
    selected_theme: str,
    current_story_json: str,
    revision_request: str,
) -> str:
    return f"""Свободно отредактируй персонализированную детскую сказку по пожеланиям автора.

Информация о ребёнке:
{child_info}

Выбранная тематика сказки:
{selected_theme}

Текущая сказка JSON:
{current_story_json}

Пожелания к редакции:
{revision_request}

Главное правило: пожелания автора имеют высший приоритет.
Можно сильно менять сказку: сокращать или увеличивать объём, менять сюжет, темп,
тон, персонажей, события, финал, распределение текста по страницам и степень детализации.
Если автор просит "сильно сократить", "меньше текста", "короче", "проще" —
обязательно сделай страницы заметно короче, даже если они станут меньше исходного шаблона.
Если автор просит радикальную правку, выполни её, а не косметически перефразируй старый текст.

Сохрани JSON-формат и последовательную нумерацию страниц.
Количество страниц по возможности сохрани прежним, но если автор явно просит изменить структуру
или количество страниц, следуй его просьбе.
Каждая страница должна оставаться понятной сценой детской книги, но объём страницы определяется правкой автора.

Верни только JSON без markdown. Формат:
{{
  "child_name": "имя ребёнка или null",
  "pages": [
    {{
      "page_number": 1,
      "page_text": "текст страницы"
    }}
  ]
}}
"""


def characters_prompt(
    child_info: str,
    selected_theme: str,
    story_json: str,
) -> str:
    return f"""Создай общий character/correction prompt для иллюстраций детской книги.

Информация о ребёнке и пожелания заказчика:
{child_info}

Выбранная тематика сказки:
{selected_theme}

Утверждённая сказка JSON:
{story_json}

На фотографиях могут быть разные персонажи и важные объекты сказки:
ребёнок, члены семьи, животные, игрушки, предметы или другие визуальные референсы.
Самостоятельно сопоставь фотографии с персонажами и объектами из сказки.

Составь единый постоянный промпт для сохранения внешности персонажей между страницами:
- перечисли главного героя и второстепенных персонажей;
- для каждого человека опиши примерный возраст, лицо, волосы, глаза, выражение, телосложение и заметные нейтральные особенности;
- для животных и игрушек опиши вид, размер, цвет, форму, характерные детали;
- не идентифицируй личности и не делай чувствительных выводов;
- если на фото есть лишние или неясные объекты, используй только то, что может быть полезно для сказки.

В конце обязательно добавь:
Стиль: высокодетализированная 3D-иллюстрация в стиле Pixar, мягкий кинематографичный свет, тёплая пастельная цветовая гамма.
"""


