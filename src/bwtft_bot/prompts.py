CHARACTER_STYLE = (
    "Стиль: высокодетализированная 3D-иллюстрация в стиле Pixar, "
    "мягкий кинематографичный свет, тёплая пастельная цветовая гамма."
)

STYLE_TEMPLATE = """Сделай иллюстрацию для страницы №{page_number}.

Формат: квадрат.
Иллюстрация: без текста.

Стиль:
сказочный,
Pixar 3D,
мягкий,
детская книга.

Дополнительные требования:
- кинематографичный свет;
- высокая детализация;
- тёплая палитра;
- единый стиль всей книги;
- сохранение внешности персонажей между страницами;
- профессиональная книжная иллюстрация;
- выразительные эмоции;
- качественная композиция."""


def final_prompt(character_prompt: str, scene_blueprint: str, page_number: int) -> str:
    return "\n\n*\n\n".join(
        [
            character_prompt,
            scene_blueprint,
            STYLE_TEMPLATE.format(page_number=page_number),
        ]
    )


